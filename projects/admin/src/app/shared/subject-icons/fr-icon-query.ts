function stripAccents(value: string): string {
  return value.normalize('NFD').replace(/\p{M}/gu, '');
}

/**
 * Transforme une saisie FR (ou déjà EN) en mots-clés Iconify (anglais).
 */
export function iconSearchQuery(raw: string): string {
  const trimmed = raw.trim();
  if (!trimmed) {
    return '';
  }
  const normalized = stripAccents(trimmed).toLowerCase().replace(/\s+/g, ' ');

  const exact = FR_TO_EN[normalized.replace(/ /g, '')] ?? FR_TO_EN[normalized];
  if (exact) {
    return exact;
  }

  const tokens = normalized.split(/[^a-z0-9]+/).filter(Boolean);
  const translated = tokens.map((token) => FR_TO_EN[token] ?? token);
  return translated.join(' ').trim();
}
